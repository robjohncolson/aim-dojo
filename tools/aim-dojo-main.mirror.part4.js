function beatSpawnDist(maxK){   // BEAT-QUANTIZED SPAWN: return a distance whose ballistic flight time is an integer # of 16th-notes (k/16 beat), so landing the shot on the orb's beat means releasing exactly k sixteenths early — a rhythmic pocket. Model: a shot at speed s that returns to ~eye height at time T covers d = s·T·√(1−(gT/2s)²). Picks uniformly among the sixteenth-values reachable within the current skill-gated range; maxK caps the lead (tanks pass a small maxK to spawn CLOSE). null → the caller falls back to the old cube-root distance.
  const s=projSpeedNow(), g=CFG.projGravity, beatLen=60/Math.max(20,state.bpm);
  const fm=CFG.deal.on?_deal.farMul:1;   // THE FAR ONES CALL (LAST QUARTER): the whole band — floor AND ceiling — moves outward, so the FEASIBLE SET shifts toward the long leads instead of the band merely widening. Raw boolean first; ×1 on every other night
  const near=CFG.rangeNear*fm, far=Math.min(CFG.rangeMax, state.range)*fm;
  const ok=[], okK=[];
  for(const k of CFG.beatSpawnSixteenths){ if(maxK && k>maxK) continue; const T=(k/16)*beatLen, r=g*T/(2*s); if(r>=1) continue; const d=s*T*Math.sqrt(1-r*r); if(d>=near && d<=far){ ok.push(d); okK.push(k); } }   // r>=1: shot can't return to height in time T at this speed → that k is unreachable now
  if(!ok.length && fm!==1){ const n0=CFG.rangeNear, f0=Math.min(CFG.rangeMax, state.range);   // …and if the shifted band reaches nothing at this tempo, the UNSHIFTED band is tried before giving up. Two reasons, both hard: the sacred beat-quantized law must never be dropped for a mood, and the null return below hands the caller a cube-root fallback that spends an EXTRA rnd() draw — a far night must not be able to add one
    for(const k of CFG.beatSpawnSixteenths){ if(maxK && k>maxK) continue; const T=(k/16)*beatLen, r=g*T/(2*s); if(r>=1) continue; const d=s*T*Math.sqrt(1-r*r); if(d>=n0 && d<=f0){ ok.push(d); okK.push(k); } } }
  if(!ok.length){ _beatSpawnK=0; return null; }
  const u=rnd(); let pick=(u*ok.length)|0;   // ONE draw, always, whatever the sky dealt
  if(CFG.sensei.on && senseiWeightLive()) pick=senseiPickK(u, okK);   // SENSEI'S ONE QUESTION: the opening swells of a night that carries a fresh observation lean the SAME number toward the weak lead — a weighted walk over the identical feasible set, no second draw and no reroll, so the stream is untouched. Raw boolean first, so an off build (and every neutral night) makes no call and no read here at all
  if(CFG.deal.on && _dealPairK>=0 && ok.length>1 && okK[pick]===_dealPairK) pick=(pick+1)%ok.length;   // THE ECHOES ANSWER IN PAIRS: a companion that drew its primary's own subdivision is nudged to the neighbouring candidate — deterministically, spending nothing — so the pair really is two release times into one arrival beat and not one distance twice
  if(CFG.poly.on && _polyK>0 && !maxK){ const pk=okK.indexOf(_polyK); if(pk>=0) pick=pk; }   // POLYRHYTHM PAIRS: this member's lead was CHOSEN, not rolled — the pair is only a polyrhythm if both k's are exactly the drawn ratio. The draw above is still TAKEN and simply discarded (a pinned spawn costs what every spawn costs), the pin is applied LAST so it outranks the sensei's weighted walk (and the dealt-pair nudge, which can never be live at the same time) on these two orbs only, and it is silent if the k is somehow not in this set — never, in practice: polyPairSpawn proved both k's against this same band, tempo and night one instruction earlier. !maxK keeps it off the TANK's close re-draw, which owns its own distance by invariant; on the shipped config a poly member can never be a tank at all (a pending fill election makes the pair stand down, and the legacy random-tank path needs tank.fillOnly:false)
  _beatSpawnK=okK[pick]; return ok[pick];   // _beatSpawnK: the subdivision this distance encodes, latched for spawnTarget to carry on the orb (THE BOW's Mandala plots radius by k). Same draw, same rnd stream — nothing about the pick changed.
}
let _beatSpawnK=0;   // k (sixteenths of lead) of the LAST beatSpawnDist() draw; 0 = unquantized fallback distance
function tankCloseDist(){   // THE FILL'S FLOOR OF LAST RESORT (spec 1.2, T5a): the closest distance a tank may legally occupy when beatSpawnDist(maxLeadSixteenths) found no quantized answer at all. Same ballistic model, evaluated at exactly maxLeadSixteenths (the LONGEST lead the tank is allowed, hence the largest distance in the capped set), then clamped into the live band: too short → the near edge, too long for this skill-gated reach → the far edge, and either way the shortest lead the range can actually hold. It draws NOTHING (no rnd(), no stream), takes the raw CFG.rangeNear rather than the dealt band because "the fill is close" outranks a LAST QUARTER's outward push, and returns null only if the shot cannot come back to eye height in that flight at all — a real impossibility rather than a merely empty feasible set, which needs a beat longer than 2·projSpeed/projGravity and so never happens at any playable tempo
  const s=projSpeedNow(), g=CFG.projGravity, T=(Math.max(1,CFG.tank.maxLeadSixteenths|0)/16)*(60/Math.max(20,state.bpm)), r=g*T/(2*s);
  if(r>=1) return null;
  const far=Math.max(CFG.rangeNear, Math.min(CFG.rangeMax, state.range));
  return Math.min(far, Math.max(CFG.rangeNear, s*T*Math.sqrt(1-r*r)));
}
